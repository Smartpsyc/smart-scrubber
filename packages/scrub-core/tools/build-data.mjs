// Builds src/auto/registry.js and src/auto/localities.js from data/raw/.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('..', import.meta.url).pathname;

const names = [...new Set(readFileSync(root + 'data/raw/registry-first-names.txt', 'utf8')
  .split('\n').map((s) => s.trim()).filter((s) => /^[\u05D0-\u05EA'"׳״\- ]{2,}$/.test(s)))].sort();
writeFileSync(root + 'src/auto/registry.js',
  `// GENERATED by tools/build-data.mjs from data/raw/registry-first-names.txt — do not edit.\n` +
  `// ${names.length} first names from the Israeli population registry (open data).\n` +
  `export const REGISTRY_NAMES = new Set(${JSON.stringify(names.join('\n'))}.split('\\n'));\n`);

const titleCase = (s) => s.toLowerCase().replace(/(^|[\s\-(])(\p{L})/gu, (_, a, b) => a + b.toUpperCase())
  .replace(/'(\p{L})/gu, (_, b) => "'" + b);
const locs = [];
for (const line of readFileSync(root + 'data/raw/cbs-localities.tsv', 'utf8').split('\n')) {
  const [heRaw, enRaw = ''] = line.split('\t');
  const he = heRaw.replace(/\s*\([^)]*\)\s*$/, '').replace(/\s*-\s*/g, '-').replace(/\s+/g, ' ').trim();
  const en = titleCase(enRaw.replace(/\s*\([^)]*\)\s*$/, '').replace(/\s*-\s*/g, '-').trim());
  if (he.length >= 2) locs.push([he, en]);
}
// Common English spellings CBS transliteration misses.
const ALIASES = {
  'ירושלים': ['Jerusalem'], 'תל אביב-יפו': ['Tel Aviv', 'Tel-Aviv', 'Tel Aviv-Yafo', 'Jaffa'], 'חיפה': ['Haifa'],
  'באר שבע': ['Beer Sheva', 'Beersheba', "Be'er Sheva"], 'ראשון לציון': ['Rishon LeZion', 'Rishon Lezion'],
  'פתח תקווה': ['Petah Tikva', 'Petach Tikva'], 'נתניה': ['Netanya'], 'אשדוד': ['Ashdod'], 'חולון': ['Holon'],
  'בני ברק': ['Bnei Brak'], 'רמת גן': ['Ramat Gan'], 'רחובות': ['Rehovot'], 'בת ים': ['Bat Yam'],
  'הרצליה': ['Herzliya'], 'כפר סבא': ['Kfar Saba'], 'חדרה': ['Hadera'], 'מודיעין-מכבים-רעות': ['Modiin', "Modi'in"],
  'רעננה': ['Raanana', "Ra'anana"], 'קריית אונו': ['Kiryat Ono'], 'נצרת': ['Nazareth'], 'עפולה': ['Afula'],
  'אילת': ['Eilat'], 'טבריה': ['Tiberias'], 'צפת': ['Safed', 'Tzfat'], 'עכו': ['Acre', 'Akko'],
  'קריית שמונה': ['Kiryat Shmona'], 'בית שמש': ['Beit Shemesh'], 'אשקלון': ['Ashkelon'],
};
// Spelling variants people actually write: קרית→קריית, "תל אביב-יפו" → also "תל אביב".
function heVariants(he) {
  const v = new Set([he]);
  for (const x of [...v]) {
    if (/(^|\s)קרית(\s|$)/.test(x)) v.add(x.replace(/(^|\s)קרית(?=\s|$)/g, '$1קריית'));
  }
  for (const x of [...v]) {
    if (x.includes('-') && x.split('-')[0].length >= 3 && x.split('-')[0].includes(' ')) v.add(x.split('-')[0]);
    if (x.includes('-')) v.add(x.replace(/-/g, ' '));
  }
  return [...v];
}
const out = locs.map(([he, en]) => {
  const hv = heVariants(he);
  const alias = hv.flatMap((h) => ALIASES[h] || []);
  return { he: hv, en: [...new Set([en, ...alias].filter(Boolean))] };
});
writeFileSync(root + 'src/auto/localities.js',
  `// GENERATED by tools/build-data.mjs from data/raw/cbs-localities.tsv — do not edit.\n` +
  `export const LOCALITIES = ${JSON.stringify(out)};\n`);
console.log('registry', names.length, 'localities', out.length,
  'aliases missing:', Object.keys(ALIASES).filter((k) => !out.some((o) => o.he.includes(k))));
